// ★ 0.237.0：长回复锚点 prompt 密度联动（任务书 §六——AI 侧随档位给密度指令）：
//   疏档（默认）全文 2~3 个、每章最多 1 个；密档全文 3~5 个、每章最多 2 个（放宽）
export function buildAnchorLongPrompt(density: string): string {
  const dense = density === 'dense';
  const densityRule = dense
    ? '每个 ## 小节最多 2 个锚点，全文总数 3~5 个'
    : '每个 ## 小节最多 1 个锚点，全文总数 2~3 个';
  return '本次回答中需要插入「注意力锚点」标记，严格遵守：\n'
    + '1. 格式：[[anchor:类型|文案]]，必须独占一行，前后各空一行；\n'
    + '2. 类型五选一：quiz=考考你（就刚讲的核心点出一句有难度的问句，禁止给出答案）、hook=前方高能（一句话吊胃口、不剧透，指向即将讲的重点）、rephrase=换个说法（把刚讲的硬核概念用一句大白话/一个比喻重说一遍）、predict=先猜再看（在推理转折处暂停，问读者“你猜下一步会怎么推”）、recap=一句话锁住（把刚讲的一段用一句话总结锁住）；\n'
    + `3. 密度：${densityRule}；相邻两个锚点类型不得重复；\n`
    + '4. 位置：只插在自然段落之间，禁止插在代码块、表格、公式、列表内部；\n'
    + '5. quiz 难度红条：禁止出“1+1”式浅题、禁止出毫无信息量的送分题；必须设计成能促使读者停下来跨知识点、反直觉、需推理才能答的高级问题，可适当提高难度甚至跨章节；\n'
    + '6. 措辞像人、禁系统腔：锚点文案必须像“一个懂你的人在递话”，禁止出现「温馨提示」「小贴士」「请注意」等系统提示腔；每句与上下文强相关，禁止通用套话、禁止重复之前用过的表述；全文最多 1 次自然使用用户的称呼；\n'
    + '7. 禁止解释标记本身，禁止输出任何关于锚点的额外说明。\n'
    + `再次强调：[[anchor:类型|文案]] 独占一行、代码块表格内禁止、${dense ? '总数 3~5 个' : '总数 2~3 个'}。`;
}

